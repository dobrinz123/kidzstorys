// Get cover image for a story
export function getCoverImage(storyId: string, category: string = "bedtime"): any {
    // First check if story has a specific cover
    if (COVER_IMAGES[storyId]) {
        return COVER_IMAGES[storyId];
    }
    // Otherwise use category placeholder
    if (CATEGORY_COVERS[category]) {
        return CATEGORY_COVERS[category];
    }
    // Default fallback
    return CATEGORY_COVERS["bedtime"];
}

